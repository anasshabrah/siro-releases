def ui(t):  # a label exactly as it appears in the program
    return f'<b class="ui">{t}</b>'

def path(*parts):
    return ui(" ← ".join(parts))

def steps(*items):
    return '<ol class="steps">' + "".join(f"<li>{i}</li>" for i in items) + "</ol>"

def shot(src, alt, cap, phone=False):
    from PIL import Image
    w, h = Image.open(os.path.join(OUT, "img", src)).size  # real size, so the page reserves the right space before it loads
    cls = ' class="phone"' if phone else ""
    return f'<figure{cls}><img src="img/{src}" width="{w}" height="{h}" loading="lazy" alt="{alt}"><figcaption>{cap}</figcaption></figure>'

def phones(*items):
    return '<div class="phones">' + "".join(shot(s, a, c, phone=True) for s, a, c in items) + "</div>"

def note(t):
    return f'<p class="note">{t}</p>'

